Die Azteken waren ein mächtiges Krieger- und Bauernvolk in Mexiko, das ein riesiges Reich aufbaute, bis es im Jahr 1521 von spanischen Eroberern zerstört wurde.
Für eine GL-Arbeit musst du das Thema aus den drei Blickwinkeln Erdkunde, Geschichte und Politik/Gesellschaft verstehen. Hier ist das Wichtigste ganz einfach zusammengefasst:

1. Erdkunde: Wo haben sie gelebt?

• Der Ort: Im heutigen Mexiko (Mittelamerika).
• Die Hauptstadt: Sie hieß Tenochtitlán (gesprochen: Tenotschtitlan).
• Das Besondere: Die Stadt wurde mitten auf einer Insel in einem großen See gebaut. Heute steht genau an dieser Stelle Mexiko-Stadt.
• Schlaue Landwirtschaft: Weil es auf einer Insel wenig Platz gab, bauten sie künstliche, schwimmende Gärten aus Schlamm und Schilf (Chinampas). Darauf wuchsen Mais, Bohnen und Chilis.

2. Geschichte: Was ist passiert?

• Der Aufstieg (ab ca. 1325): Die Azteken wanderten als armes Volk ein, gründeten ihre Hauptstadt und eroberten durch Kriege fast alle Nachbarstämme.
• Die Spanier kommen (1519): Der spanische Eroberer Hernán Cortés landete mit Soldaten, Pferden und Feuerwaffen in Mexiko. Er suchte nach Gold.
• Der Untergang (1521): Die Azteken hatten gegen die modernen Waffen, die Rüstungen und vor allem gegen eingeschleppte Krankheiten (wie die Pocken) keine Chance. Cortés eroberte das Reich und zerstörte die Hauptstadt.

3. Politik & Gesellschaft: Wie haben sie gelebt?

• Strenge Ordnung: Ganz oben stand der Herrscher (wie ein Kaiser), darunter kamen Priester und Krieger. Ganz unten waren einfache Bauern und Sklaven.
• Religion und Opfer: Die Azteken glaubten an viele Götter (z. B. den Sonnengott). Damit die Sonne jeden Tag wieder aufgeht, brachten sie den Göttern Menschenopfer dar – meistens Kriegsgefangene.
• Warum sie verloren haben: Weil die Azteken ihre Nachbarvölker unterdrückten und für Opfer gefangen nahmen, hassten diese Nachbarn die Azteken. Als die Spanier kamen, verbündeten sich diese Stämme mit Cortés gegen die Azteken.

